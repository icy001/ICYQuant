"""
Continuous Evaluation
=====================
Ongoing strategy monitoring even after promotion to live.

Monitors:
    - Performance drift vs paper trading baseline
    - Risk metric degradation
    - Regime change impact
    - Capacity limits

Pipeline:
    Performance → Drift → Risk → Recommendation
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4

logger = logging.getLogger(__name__)


class EvaluationStatus(str, Enum):
    HEALTHY = "HEALTHY"
    WATCHING = "WATCHING"
    DEGRADING = "DEGRADING"
    CRITICAL = "CRITICAL"
    UNKNOWN = "UNKNOWN"


@dataclass
class EvaluationWindow:
    """A rolling evaluation window."""
    window_days: int = 30
    start_date: Optional[datetime] = None
    end_date: Optional[datetime] = None
    metrics: Dict[str, Any] = field(default_factory=dict)
    status: EvaluationStatus = EvaluationStatus.UNKNOWN


@dataclass
class EvaluationAlert:
    """An alert generated by continuous evaluation."""
    alert_id: str = field(default_factory=lambda: f"eval_{uuid4().hex[:8]}")
    strategy_id: str = ""
    status: EvaluationStatus = EvaluationStatus.WATCHING
    metric_name: str = ""
    current_value: float = 0.0
    baseline_value: float = 0.0
    drift_pct: float = 0.0
    message: str = ""
    recommendation: str = ""
    created_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    acknowledged: bool = False


class ContinuousEvaluation:
    """Ongoing strategy evaluation and drift detection.

    Pipeline:
        Performance → Drift → Risk → Recommendation
    """

    def __init__(self):
        self._baselines: Dict[str, Dict[str, Any]] = {}  # strategy → baseline metrics
        self._history: Dict[str, List[Dict[str, Any]]] = {}  # strategy → metric snapshots
        self._alerts: List[EvaluationAlert] = []
        self._drift_thresholds: Dict[str, float] = {
            "sharpe_decline_pct": 0.30,       # 30% decline in Sharpe
            "drawdown_increase_pct": 0.50,    # 50% increase in max drawdown
            "win_rate_decline_pct": 0.20,     # 20% decline in win rate
            "volatility_increase_pct": 0.50,  # 50% increase in volatility
        }
        self.is_initialized = False

    async def initialize(self) -> None:
        self.is_initialized = True
        logger.info("ContinuousEvaluation initialized")

    # ------------------------------------------------------------------
    # Baseline Management
    # ------------------------------------------------------------------

    async def set_baseline(self, strategy_id: str,
                           metrics: Dict[str, Any]) -> None:
        """Set the paper trading baseline for a strategy."""
        self._baselines[strategy_id] = dict(metrics)
        logger.info("Baseline set for strategy %s", strategy_id)

    # ------------------------------------------------------------------
    # Evaluation
    # ------------------------------------------------------------------

    async def evaluate(self, strategy_id: str,
                       current_metrics: Dict[str, Any]) -> EvaluationStatus:
        """Evaluate current performance against baseline."""
        baseline = self._baselines.get(strategy_id)
        if not baseline:
            return EvaluationStatus.UNKNOWN

        # Store history
        if strategy_id not in self._history:
            self._history[strategy_id] = []
        self._history[strategy_id].append({
            "timestamp": datetime.now(timezone.utc).isoformat(),
            **current_metrics,
        })

        alerts = []
        worst_status = EvaluationStatus.HEALTHY

        # Check Sharpe drift
        if "sharpe_ratio" in baseline and "sharpe_ratio" in current_metrics:
            base_sharpe = baseline["sharpe_ratio"]
            current_sharpe = current_metrics["sharpe_ratio"]
            if base_sharpe > 0 and current_sharpe < base_sharpe * 0.5:
                decline = (base_sharpe - current_sharpe) / base_sharpe
                if decline > self._drift_thresholds["sharpe_decline_pct"]:
                    status = EvaluationStatus.CRITICAL if decline > 0.5 else EvaluationStatus.DEGRADING
                    worst_status = max(worst_status, status, key=self._status_severity)
                    alerts.append(EvaluationAlert(
                        strategy_id=strategy_id,
                        status=status,
                        metric_name="sharpe_ratio",
                        current_value=current_sharpe,
                        baseline_value=base_sharpe,
                        drift_pct=decline * 100,
                        message=f"Sharpe declined {decline*100:.1f}%: {base_sharpe:.2f} → {current_sharpe:.2f}",
                        recommendation="Review strategy logic and market conditions",
                    ))

        # Check drawdown
        if "max_drawdown" in baseline and "max_drawdown" in current_metrics:
            base_dd = abs(baseline["max_drawdown"])
            current_dd = abs(current_metrics["max_drawdown"])
            if current_dd > base_dd * 2:
                increase = (current_dd - base_dd) / max(base_dd, 0.01)
                if increase > self._drift_thresholds["drawdown_increase_pct"]:
                    status = EvaluationStatus.DEGRADING
                    worst_status = max(worst_status, status, key=self._status_severity)
                    alerts.append(EvaluationAlert(
                        strategy_id=strategy_id,
                        status=status,
                        metric_name="max_drawdown",
                        current_value=current_dd,
                        baseline_value=base_dd,
                        drift_pct=increase * 100,
                        message=f"Drawdown increased {increase*100:.1f}%: {base_dd:.4f} → {current_dd:.4f}",
                        recommendation="Consider reducing position sizes or pausing strategy",
                    ))

        # Check win rate
        if "win_rate" in baseline and "win_rate" in current_metrics:
            base_wr = baseline["win_rate"]
            current_wr = current_metrics["win_rate"]
            if current_wr < base_wr * 0.7:
                decline = (base_wr - current_wr) / max(base_wr, 0.01)
                if decline > self._drift_thresholds["win_rate_decline_pct"]:
                    status = EvaluationStatus.DEGRADING
                    worst_status = max(worst_status, status, key=self._status_severity)
                    alerts.append(EvaluationAlert(
                        strategy_id=strategy_id,
                        status=status,
                        metric_name="win_rate",
                        current_value=current_wr,
                        baseline_value=base_wr,
                        drift_pct=decline * 100,
                        message=f"Win rate declined {decline*100:.1f}%: {base_wr:.4f} → {current_wr:.4f}",
                        recommendation="Analyze losing trades for pattern changes",
                    ))

        self._alerts.extend(alerts)
        if alerts:
            logger.warning("Continuous evaluation for %s: %s (%d alerts)",
                           strategy_id, worst_status.value, len(alerts))

        return worst_status

    # ------------------------------------------------------------------
    # Recommendations
    # ------------------------------------------------------------------

    async def generate_recommendation(self, strategy_id: str) -> Dict[str, Any]:
        """Generate a recommendation based on continuous evaluation."""
        status = EvaluationStatus.UNKNOWN
        recent = self._history.get(strategy_id, [])
        if recent:
            status = await self.evaluate(strategy_id, recent[-1])

        recommendations = {
            EvaluationStatus.HEALTHY: "Strategy performing within expectations. No action needed.",
            EvaluationStatus.WATCHING: "Monitor closely. Minor deviations detected.",
            EvaluationStatus.DEGRADING: "Consider reducing allocation. Investigate drift causes.",
            EvaluationStatus.CRITICAL: "IMMEDIATE ACTION: Pause strategy. Conduct full review.",
            EvaluationStatus.UNKNOWN: "Insufficient data for evaluation.",
        }

        return {
            "strategy_id": strategy_id,
            "status": status.value,
            "recommendation": recommendations.get(status, ""),
            "recent_alerts": len([a for a in self._alerts
                                  if a.strategy_id == strategy_id and not a.acknowledged]),
        }

    # ------------------------------------------------------------------
    # Query
    # ------------------------------------------------------------------

    def recent_alerts(self, limit: int = 50) -> List[EvaluationAlert]:
        return self._alerts[-limit:]

    def unacknowledged_alerts(self) -> List[EvaluationAlert]:
        return [a for a in self._alerts if not a.acknowledged]

    def get_baseline(self, strategy_id: str) -> Optional[Dict[str, Any]]:
        return self._baselines.get(strategy_id)

    def get_metrics(self) -> Dict[str, Any]:
        return {
            "strategies_tracked": len(self._baselines),
            "total_alerts": len(self._alerts),
            "unacknowledged_alerts": len(self.unacknowledged_alerts()),
            "drift_thresholds": dict(self._drift_thresholds),
        }

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _status_severity(status: EvaluationStatus) -> int:
        order = {
            EvaluationStatus.HEALTHY: 0,
            EvaluationStatus.WATCHING: 1,
            EvaluationStatus.DEGRADING: 2,
            EvaluationStatus.CRITICAL: 3,
            EvaluationStatus.UNKNOWN: -1,
        }
        return order.get(status, -1)
