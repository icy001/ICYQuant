@pytest.mark.skipif(
    not REAL_NATIVE_JSON.exists(),
    reason="real K01 backtest artifact not on disk",
)
def test_real_artifact_full_chain(tmp_path: Path):
    events, source = load_events(REAL_NATIVE_JSON)

    assert source == "lean-native-json"

    fills = [
        map_order_event(e) for e in events
        if map_order_event(e)["status"] in FILL_STATUSES
        and map_order_event(e)["filled_quantity"]
        and map_order_event(e)["fill_price"]
    ]

    assert len(fills) == 1
    fill = fills[0]

    # signal_id recovered from the sibling log evidence (K01 + K02)
    assert fill["signal_id"] == "p0_buy_spy"
    assert fill["symbol"] == "SPY"
    assert float(fill["fill_price"]) == pytest.approx(144.78172417)
    assert fill["filled_quantity"] == 100

    # commission forwarded from the native orderFeeAmount
    raw_fill = next(
        e for e in events
        if e.get("status") == "FILLED" and e.get("fill_price")
    )
    assert raw_fill.get("commission") == 1.0

    trade = order_event_to_ledger_trade(
        raw_fill, commission=raw_fill.get("commission") or 0
    )

    assert trade.quantity == Decimal("100")
    assert trade.price == Decimal("144.78172417")
    assert trade.commission == Decimal("1.0")

    journal = PostingEngine().post_trade(trade)

    assert journal.is_balanced()


@pytest.mark.skipif(
    not REAL_NATIVE_JSON.exists(),
    reason="real K01 backtest artifact not on disk",
)
def test_real_artifact_g07_g08_pass(tmp_path: Path):
    """The full G07 → G08 → reconciliation chain via the real runner."""
    runner = LeanPaperE2E(
        tmp_path / "artifacts",
        REPO_ROOT,
        events_path=REAL_NATIVE_JSON,
    )

    results = {r.gate: r for r in runner.run(only=["G07", "G08"])}

    g07 = results["G07"]
    g08 = results["G08"]

    assert g07.status == STATUS_PASS, g07.detail
    assert g08.status == STATUS_PASS, g08.detail

    # expected signed quantity == actual signed fill quantity
    reconciliation = json.loads(
        (tmp_path / "artifacts" / "reconciliation.json").read_text(
            encoding="utf-8"
        )
    )

    assert reconciliation["reconciled"] is True
    assert reconciliation["problems"] == []
    assert reconciliation["expected"] == {"p0_buy_spy": "100"}
    assert reconciliation["matched"] == [
        {"signal_id": "p0_buy_spy", "signed_quantity": "100"}
    ]

    # commission visible in the journal record
    assert reconciliation["journals"][0]["commission"] == "1.0"
    assert reconciliation["journals"][0]["balanced"] is True
