def test_commission_flows_to_ledger_trade():
    adapted = adapt_native_order_events([_native_buy_fill()])

    trade = order_event_to_ledger_trade(
        adapted[0], commission=adapted[0].get("commission") or 0
    )

    assert trade.commission == Decimal("1.0")


def test_commission_writes_commission_journal_entry():
    trade = order_event_to_ledger_trade(
        adapt_native_order_events([_native_buy_fill()])[0],
        commission=1.0,
    )

    journal = PostingEngine().post_trade(trade)

    entries = journal.entries
    commission_debits = [
        e for e in entries
        if str(getattr(e, "account_code", getattr(e, "account", ""))) == "commission"
        or "COMMISSION" in str(getattr(e, "account_code", ""))
        or "commission" in str(e).lower()
    ]

    assert journal.is_balanced()
    # The trade-side commission journal only exists when commission > 0
    # was forwarded; a 0-commission trade produces exactly 2 entries.
    assert trade.commission == Decimal("1.0")
    assert len(entries) > 2, "COMMISSION journal entries missing"


