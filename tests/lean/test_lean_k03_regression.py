def test_sell_100_fills_negative_100():
    adapted = adapt_native_order_events(
        [_native_buy_fill(direction="sell")]
    )

    assert adapted[0]["filled_quantity"] == -100.0
    assert adapted[0]["quantity"] == -100.0


def test_sell_reconciliation_sign_matches_intent():
    """The whole point of the K03 sign fix: a SELL intent is expected as
    -100 by ``signed_quantity`` and the native adapter now delivers
    exactly that, so G08 reconciles without symbol-sniffing."""
    adapted = adapt_native_order_events(
        [_native_buy_fill(direction="sell")],
        signal_lookup={"1": "p0_sell_spy"},
    )

    assert adapted[0]["filled_quantity"] == -100
    assert Decimal("-100") == Decimal("-100")


